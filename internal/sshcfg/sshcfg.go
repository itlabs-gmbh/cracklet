// Package sshcfg renders the ssh_config that lets `ssh <vm>.cracklet` reach a
// microVM through the backend's ProxyCommand.
package sshcfg

import (
	"bytes"
	"fmt"
	"strings"
	"text/template"
)

// Options parameterise the rendered configuration.
type Options struct {
	// Instance is the host alias suffix; hosts are addressed as <vm>.<Instance>.
	Instance string
	// KeyPath is the private key injected into every microVM.
	KeyPath string
	// ProxyCommand is the backend's way to the guest, with ssh's %h and %p
	// placeholders for host and port.
	ProxyCommand string
	// KnownHostsFile, when set, holds the pinned host key of every microVM
	// and turns strict host key checking on. Empty means the backend cannot
	// pin keys (the Lima guests share one image-wide key behind a firewall)
	// and ssh accepts whatever key it sees.
	KnownHostsFile string
}

var tmpl = template.Must(template.New("ssh_config").Parse(`# Generated by cracklet. Reach microVMs with: ssh <name>.{{.Instance}}
# Add "Include {{.Path}}" to ~/.ssh/config to use the alias with plain ssh.
Host *.{{.Instance}}
  User root
  IdentityFile {{.KeyPath}}
  ProxyCommand {{.ProxyCommand}}
{{- if .KnownHostsFile}}
  StrictHostKeyChecking yes
  UserKnownHostsFile {{.KnownHostsFile}}
{{- else}}
  StrictHostKeyChecking no
  UserKnownHostsFile /dev/null
{{- end}}
  LogLevel ERROR
`))

// Render produces the ssh_config text.
func Render(o Options) (string, error) {
	if o.Instance == "" || o.KeyPath == "" || o.ProxyCommand == "" {
		return "", fmt.Errorf("instance, key path and proxy command are required")
	}
	if strings.ContainsAny(o.ProxyCommand+o.KeyPath+o.KnownHostsFile, "\n\r") {
		return "", fmt.Errorf("ssh_config values must not contain line breaks")
	}
	var buf bytes.Buffer
	data := struct {
		Options
		Path string
	}{Options: o, Path: "~/.cracklet/ssh_config"}
	if err := tmpl.Execute(&buf, data); err != nil {
		return "", fmt.Errorf("render ssh config: %w", err)
	}
	return buf.String(), nil
}

// HostAlias returns the ssh host name for a microVM.
func HostAlias(name, instance string) string {
	return name + "." + instance
}

// VMName is the inverse of HostAlias: it strips the alias suffix ssh passes
// as %h to the ProxyCommand. A bare name is accepted as well.
func VMName(host, instance string) string {
	return strings.TrimSuffix(host, "."+instance)
}
